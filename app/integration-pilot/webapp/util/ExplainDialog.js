sap.ui.define(
  [
    'sap/m/Dialog',
    'sap/m/Button',
    'sap/m/VBox',
    'sap/m/HBox',
    'sap/m/Title',
    'sap/m/Text',
    'sap/m/BusyIndicator',
    'sap/m/MessageStrip',
    'sap/m/FormattedText',
    'sap/m/ObjectStatus',
    'sap/ui/core/HTML',
    'integration/pilot/util/api',
    'integration/pilot/util/flowDiagram',
    'integration/pilot/util/markdown'
  ],
  (Dialog, Button, VBox, HBox, Title, Text, BusyIndicator, MessageStrip, FormattedText, ObjectStatus, HTML, api, flowDiagram, markdown) => {
    'use strict'

    /**
     * "Explain with AI" for an iFlow on the tenant ({ iflowId }) or an uploaded zip ({ zipBase64 }):
     * shows the parsed flow as a diagram and the AI explanation. If the AI is unavailable the
     * parsed structure is still shown.
     */
    function open(view, { iflowId, zipBase64, label }) {
      const busy = new BusyIndicator({ text: 'Reading the iFlow and asking the AI…', size: '2rem' })
      const content = new VBox({ items: [busy], renderType: 'Bare' }).addStyleClass('sapUiSmallMargin ipGapM')
      const started = Date.now()
      const timer = setInterval(() => busy.setText(`Reading the iFlow and asking the AI… ${Math.round((Date.now() - started) / 1000)}s`), 1000)

      const dialog = new Dialog({
        title: `Explain ${label}`,
        icon: 'sap-icon://lightbulb',
        contentWidth: '64rem',
        contentHeight: '70%',
        resizable: true,
        draggable: true,
        content,
        endButton: new Button({ text: 'Close', press: () => dialog.close() }),
        afterClose: () => {
          clearInterval(timer)
          dialog.destroy()
        }
      })
      view.addDependent(dialog)
      dialog.open()

      api
        .post('/explain', zipBase64 ? { zipBase64 } : { iflowId })
        .then((r) => {
          const s = r.summary
          content.removeAllItems()
          content.addItem(
            new HBox({
              alignItems: 'Center',
              renderType: 'Bare',
              items: [new Title({ text: s.name || label, level: 'H3' }), new ObjectStatus({ text: s.id || '' }).addStyleClass('ipMono sapUiSmallMarginBegin')]
            })
          )
          content.addItem(new HTML({ content: `<div class="ipFlowBox">${flowDiagram.toHtml(flowDiagram.fromParsed(s))}</div>`, sanitizeContent: false }))
          if (r.explanation) {
            content.addItem(new FormattedText({ htmlText: markdown.toHtml(r.explanation) }).addStyleClass('ipBubbleText'))
            if (r.model) content.addItem(new Text({ text: `Generated by ${r.model}. AI output can be wrong — verify before acting.` }).addStyleClass('ipSubtle'))
          } else if (r.error) {
            content.addItem(new MessageStrip({ type: 'Warning', showIcon: true, text: `The AI explanation is not available right now: ${r.error.message} The parsed structure above is still accurate.` }))
          }
        })
        .catch((e) => {
          content.removeAllItems()
          content.addItem(new MessageStrip({ type: 'Error', showIcon: true, text: e.hint ? `${e.message} — ${e.hint}` : e.message }))
        })
        .finally(() => clearInterval(timer))
    }

    return { open }
  }
)
